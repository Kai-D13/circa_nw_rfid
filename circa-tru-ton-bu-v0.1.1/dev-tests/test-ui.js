// E2E giao diện: nạp extension thật vào Chromium, giả lập POS v2 + Nextwaves bằng route. node test-ui.js <ext> <outdir>
const { chromium } = require("playwright");
const path = require("path");
const fs = require("fs");
const os = require("os");
const assert = require("assert");
const EXT = path.resolve(process.argv[2]);
const OUT = path.resolve(process.argv[3] || ".");
const STORE = "c476efb2-415c-429a-978e-d389b4b06607";
const U_DIA = "1e4c377d-fb9d-4b3d-aa14-65b67b85c2bf";
const EPC = "1784593522634C06FFFFFFFF";
const IDS = ["11111111-1111-4111-8111-111111111111", "22222222-2222-4222-8222-222222222222", "33333333-3333-4333-8333-333333333333"];
const CODES = ["DHC01300001", "DHC01300002", "DHC01299037"];
const order = (i) => ({ success: true, data: { order: { id: IDS[i], code: CODES[i], status: "COMPLETED", type: "OFFLINE", pos_id: STORE, created_date: "2026-10-25T0" + (i + 1) + ":00:00.000Z", completed_date: "2026-10-25T0" + (i + 1) + ":00:00.000Z", updated_date: "2026-10-25T0" + (i + 1) + ":00:00.000Z", customer_name: "KHÔNG ĐƯỢC LƯU", items: [{ id: IDS[i].replace(/^.{8}/, "aaaaaaaa"), product_id: 8278, sku_code: "CIRCA.UNI-DIA-001", product_name: "Băng vệ sinh Diana", quantity: 1, unit: "gói", unit_id: U_DIA, base_quantity: 8, qr_code: "1784593522634C5", qr_codes: ["1784593522634C5"], product: { name: "Băng vệ sinh Diana", lots: [{ big: "x".repeat(50) }], retail_units: [{ id: U_DIA, unit: "gói", convert_rate: 8, base_unit: false }, { id: "33333333-3333-4333-8333-333333333334", unit: "miếng", convert_rate: 1, base_unit: true }] } }] } } });
const log = (i) => ({ success: true, data: { total: 1, list: [{ id: IDS[i].replace(/^.{8}/, "bbbbbbbb"), action: "ITEM_ADDED", status: "SUCCESS", created_at: "2026-10-25T0" + (i + 1) + ":00:00.000Z", detail: { args: ["1", 10000] }, metadata: { product_id: "8278", qr_code: "1784593522634C5", sku_code: "CIRCA.UNI-DIA-001", unit: "gói", via: "qr" } }] } });
const CORS = { "access-control-allow-origin": "*", "access-control-allow-headers": "*", "access-control-allow-methods": "GET,POST,OPTIONS", "access-control-expose-headers": "idempotent-replay" };

(async () => {
  const userDir = fs.mkdtempSync(path.join(os.tmpdir(), "bf-ui-"));
  const ctx = await chromium.launchPersistentContext(userDir, { channel: "chromium", headless: true, args: ["--disable-extensions-except=" + EXT, "--load-extension=" + EXT], viewport: { width: 1360, height: 900 } });
  const nwCalls = [];
  let held = 12;
  const nwOrders = {};
  await ctx.route("https://pos.v2.circa.vn/**", (r) => r.fulfill({ status: 200, contentType: "text/html", body: "<html><body>POS giả</body></html>" }));
  await ctx.route("https://api.v2.circa.vn/**", (r) => {
    if (r.request().method() === "OPTIONS") return r.fulfill({ status: 204, headers: CORS });
    const u = r.request().url();
    const i = IDS.findIndex((id) => u.indexOf(id) >= 0);
    assert.ok(r.request().headers()["x-store-id"] === STORE);
    const body = u.indexOf("/activity-log/") >= 0 ? log(i) : order(i);
    return r.fulfill({ status: 200, headers: CORS, contentType: "application/json", body: JSON.stringify(body) });
  });
  await ctx.route("https://api-circa.nextwaves.app/**", (r) => {
    const req = r.request();
    if (req.method() === "OPTIONS") return r.fulfill({ status: 204, headers: CORS });
    const p = new URL(req.url()).pathname.replace("/api/v1/public", "");
    nwCalls.push({ m: req.method(), p, h: req.headers(), b: req.postData() });
    const j = (s, b, extra) => r.fulfill({ status: s, headers: Object.assign({}, CORS, extra || {}), contentType: "application/json", body: JSON.stringify(b) });
    if (p === "/me") return j(200, { keyId: "nwc_pk_test", name: "STOCK-SYNC-BATCH", scopes: ["read", "write"] });
    if (p.startsWith("/orders/")) return nwOrders[p.slice(8)] ? j(200, nwOrders[p.slice(8)]) : j(404, { message: "ORDER_NOT_FOUND" });
    if (p === "/tags/by-uid/1784593522634C5") return j(200, { uid: "1784593522634C5", mapped: true, epc: EPC, status: "active" });
    if (p.startsWith("/integrations/circa/epcs/")) return j(200, { epc: EPC, found: true, status: held > 0 ? "active" : "sold", unitUid: "1784593522634C5", circaProductId: "8278", unit: "miếng", unitRatio: 1, baseUnit: "miếng", baseQuantity: held });
    if (p === "/integrations/circa/orders/notify" && req.method() === "POST") {
      const b = JSON.parse(req.postData());
      held -= b.tags.reduce((a, t) => a + t.quantity, 0);
      nwOrders[b.orderId] = { orderNumber: "CIR-" + b.orderId, items: b.tags.map((t) => ({ tagEpc: t.epc, baseQuantity: t.quantity })) };
      return j(201, { success: true, imported: true, orderId: "nw-1", externalOrderId: b.orderId, stockOut: { outcome: "STOCKED_OUT" }, settledEpcs: b.tags.map((t) => t.epc) }, { "idempotent-replay": "false" });
    }
    return j(500, {});
  });
  await ctx.addCookies([{ name: "session_token", value: "dGVzdA%3D%3D", domain: "pos.v2.circa.vn", path: "/", secure: true }]);
  const pos = await ctx.newPage();
  await pos.goto("https://pos.v2.circa.vn/dashboard");
  let sw = ctx.serviceWorkers()[0];
  if (!sw) sw = await ctx.waitForEvent("serviceworker");
  const extId = sw.url().split("/")[2];
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e)));
  page.on("dialog", (d) => d.accept());
  await page.goto("chrome-extension://" + extId + "/tool.html");
  await page.click("#btnSettings");
  await page.fill("#sKey", "nwc_pk_test:nwc_sk_test");
  await page.click("#btnCheckKey");
  await page.waitForFunction(() => document.querySelector("#pKey").textContent.indexOf("write") >= 0);
  await page.fill("#input", "order_code,order_id\n" + CODES.map((c, i) => c + "," + IDS[i]).join("\n"));
  await page.click("#btnCheck");
  await page.waitForFunction(() => document.querySelectorAll("#tbl tbody tr").length === 3, null, { timeout: 20000 });
  const rows = await page.$$eval("#tbl tbody tr", (trs) => trs.map((t) => t.innerText.replace(/\s+/g, " ")));
  console.log(rows.join("\n"));
  assert.ok(rows.some((r) => r.indexOf("DHC01300001") >= 0 && r.indexOf("Đủ điều kiện") >= 0));
  assert.ok(rows.some((r) => r.indexOf("DHC01300002") >= 0 && r.indexOf("Cần xem lại") >= 0), "tem còn 12 → đơn thứ 2 không đủ");
  assert.ok(rows.some((r) => r.indexOf("DHC01299037") >= 0 && r.indexOf("Bị chặn") >= 0));
  assert.strictEqual(await page.isDisabled("#btnSend"), true);
  await page.click("#btnSelAll");
  await page.check("#sAllow");
  await page.waitForFunction(() => document.querySelector("#pSend").textContent.indexOf("BẬT") >= 0);
  await page.check("#cAuto");
  assert.strictEqual(await page.isDisabled("#btnSend"), false);
  await page.screenshot({ path: path.join(OUT, "ui-check.png"), fullPage: true });
  await page.click("#btnSend");
  await page.fill("#mConfirm", "1");
  await page.click("#mOk");
  await page.waitForFunction(() => document.querySelector("#hist tbody tr") && document.querySelector("#hist tbody").innerText.indexOf("confirmed") >= 0, null, { timeout: 20000 });
  const post = nwCalls.find((c) => c.m === "POST");
  assert.ok(post, "phải có POST");
  assert.strictEqual(post.h["idempotency-key"], "DHC01300001");
  assert.strictEqual(post.b, JSON.stringify({ orderId: "DHC01300001", tags: [{ epc: EPC, quantity: 8 }] }));
  assert.strictEqual(nwCalls.filter((c) => c.m === "POST").length, 1);
  const store = await sw.evaluate(() => chrome.storage.local.get(null));
  assert.ok(!JSON.stringify(store).includes("KHÔNG ĐƯỢC LƯU"), "không lưu thông tin khách");
  assert.strictEqual(store["bf:DHC01300001"].reconcile, "match");
  await page.screenshot({ path: path.join(OUT, "ui-sent.png"), fullPage: true });
  await page.click("#tbl tbody tr:first-child td:nth-child(3)");
  await page.waitForSelector("#drawer:not(.hidden)");
  await page.screenshot({ path: path.join(OUT, "ui-detail.png") });
  assert.deepStrictEqual(errors, []);
  console.log("UI OK: kiểm tra, chọn, gửi 1 đơn, Idempotency-Key, đối soát khớp, không lỗi JS");
  await ctx.close();
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
